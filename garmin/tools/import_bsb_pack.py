#!/usr/bin/env python3
"""Regenerate garmin/resources/bsb/*.json + bsb.xml + source/BsbIndex.mc from the Flipper
bsb.pack (BSB1 header, 10-byte records <BBHHI book,chapter,csize,rawsize,offset>, heatshrink).
Usage: git show origin/main:bible_bsb/assets/bsb.pack > /tmp/bsb.pack; python3 tools/import_bsb_pack.py /tmp/bsb.pack
Needs: pip install heatshrink2"""
import struct, sys, os, json, heatshrink2
here = os.path.dirname(os.path.abspath(__file__)); root = os.path.dirname(here)
b = open(sys.argv[1], 'rb').read()
magic, count, rs, w, l, _ = struct.unpack('<4sHHBBH', b[:12]); assert magic == b'BSB1'
recs = [struct.unpack('<BBHHI', b[12+i*10:22+i*10]) for i in range(count)]
out = os.path.join(root, 'resources', 'bsb'); os.makedirs(out, exist_ok=True)
xml = ['<?xml version="1.0" encoding="UTF-8"?>', '<!-- GENERATED by tools/import_bsb_pack.py from Flipper assets/bsb.pack. Do not edit. -->', '<resources>']
books = {}
for bk, ch, cs, raw, off in recs:
    j = json.loads(heatshrink2.decompress(b[off:off+cs], window_sz2=w, lookahead_sz2=l).decode('utf-8'))
    fn = f'b{bk:02d}c{ch:03d}.json'
    open(os.path.join(out, fn), 'w').write(json.dumps(j, ensure_ascii=False, separators=(',', ':')))
    xml.append(f'    <jsonData id="B{bk}C{ch}" filename="{fn}"/>'); books.setdefault(bk, []).append(ch)
# PERF: per-book first-heading index (grid subtitle) -> one small resource per book, loaded once.
heads = {}
for bk, ch, cs, raw, off in recs:
    j = json.loads(open(os.path.join(out, f'b{bk:02d}c{ch:03d}.json')).read())
    h = next((v.get('h') for v in j['verses'] if v.get('h')), '')
    heads.setdefault(bk, {})[ch] = h
for bk in sorted(heads):
    fn = f'h{bk:02d}.json'
    open(os.path.join(out, fn), 'w').write(json.dumps([heads[bk][c] for c in sorted(heads[bk])], ensure_ascii=False, separators=(',', ':')))
    xml.append(f'    <jsonData id="H{bk}" filename="{fn}"/>')
xml.append('</resources>'); open(os.path.join(out, 'bsb.xml'), 'w').write('\n'.join(xml) + '\n')
src = ['using Toybox.Lang;', '', "//! GENERATED by tools/import_bsb_pack.py: (book, chapter) -> bundled BSB chapter resource.", "//! Only the requested book's array is built (on demand, per call).", 'module BsbIndex {', '    function rez(book as Lang.Number, chapter as Lang.Number) as Lang.ResourceId or Null {', '        var a = null;', '        switch (book) {']
for bk in sorted(books):
    chs = sorted(books[bk]); assert chs == list(range(1, len(chs)+1))
    src.append(f'            case {bk}: a = [' + ', '.join(f'Rez.JsonData.B{bk}C{c}' for c in chs) + ']; break;')
src += ['        }', '        if (a == null || chapter < 1 || chapter > a.size()) {', '            return null;', '        }', '        return a[chapter - 1] as Lang.ResourceId;', '    }', '',
        '    //! First section heading per chapter of a book ("" = none), one small resource.',
        '    function heads(book as Lang.Number) as Lang.ResourceId or Null {', '        switch (book) {']
src += [f'            case {bk}: return Rez.JsonData.H{bk};' for bk in sorted(books)]
src += ['        }', '        return null;', '    }', '}']
open(os.path.join(root, 'source', 'BsbIndex.mc'), 'w').write('\n'.join(src) + '\n')
print(len(books), 'books', count, 'chapters')
