#!/usr/bin/env bash
# Personal sideload build: writes PersonalSync.mc (sync key from $SELAH_VAULT_SYNC_KEY) plus a
# jungle overlay into OUTDIR (default ./tmp-personal/src under garmin/, gitignored, mode 700).
# The key is never echoed or logged; the file is mode 600.
# usage: SELAH_VAULT_SYNC_KEY=... tools/make_personal_sync.sh [OUTDIR]
#   then: monkeyc -f "monkey.jungle;OUTDIR/personal.jungle" -d enduro3 -r ...
set -euo pipefail
OUT=${1:-$(cd "$(dirname "$0")/.." && pwd)/tmp-personal/src}
umask 077
mkdir -p "$OUT"; chmod 700 "$OUT"
OUT="$OUT" python3 - <<'PY'
import os, re, sys
k = os.environ.get("SELAH_VAULT_SYNC_KEY", "").strip()
if not k:
    sys.exit("SELAH_VAULT_SYNC_KEY is not set")
if not re.fullmatch(r"[A-Za-z0-9-]{8,128}", k):
    sys.exit("SELAH_VAULT_SYNC_KEY has unexpected characters (not printed)")
out = os.environ["OUT"]
p = os.path.join(out, "PersonalSync.mc")
fd = os.open(p, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
with os.fdopen(fd, "w") as f:
    f.write("using Toybox.Lang;\n\n// GENERATED by tools/make_personal_sync.sh. Holds a sync key: never commit or share.\n"
            "(:personal)\nmodule PersonalSync {\n    function key() as Lang.String or Null {\n"
            '        return "' + k + '";\n    }\n}\n')
with open(os.path.join(out, "personal.jungle"), "w") as f:
    f.write("# GENERATED: personal build overlay (adds PersonalSync.mc, drops the committed stub).\n"
            "base.sourcePath = $(base.sourcePath);" + out + "\n"
            "enduro3.excludeAnnotations = amoled;lightmenu;sysregular;hwtest;keystub\n"
            "fr265.excludeAnnotations = mip;lightmenu;sysbold;hwtest;keystub\n")
print("wrote PersonalSync.mc (key length %d) and personal.jungle to %s" % (len(k), out))
PY
